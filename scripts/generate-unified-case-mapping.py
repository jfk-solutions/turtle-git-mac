#!/usr/bin/env python3
"""Extract pinned Scintilla lower/upper and word classes; --check verifies all scalars with C++."""
import argparse,ast,csv,hashlib,json,re,subprocess,tempfile
from pathlib import Path
root=Path(__file__).resolve().parent.parent
pin=json.loads((root/'docs/upstream.json').read_text())['commit']
with (root/'docs/upstream-files.csv').open(newline='') as f: blobs={r['path']:r['blob'] for r in csv.DictReader(f)}
def source(name):
 path='ext/scintilla/src/'+name
 data=subprocess.check_output(['git','-C',str(root/'.upstream/TortoiseGit'),'show',pin+':'+path])
 assert hashlib.sha1(b'blob '+str(len(data)).encode()+b'\0'+data).hexdigest()==blobs[path],path
 return data.decode('utf-8-sig').replace('\r\n','\n')
def ints(text,name):
 block=re.search(r'\b'+name+r'\[\]\s*=\s*\{(.*?)\};',text,re.S)[1]
 return [int(v) for v in re.findall(r'-?\d+',re.sub(r'//[^\n]*','',block))]
def maps(text):
 lower,upper={},{}
 ranges=ints(text,'symmetricCaseConversionRanges')
 for i in range(0,len(ranges),4):
  lo,hi,n,pitch=ranges[i:i+4]
  for offset in range(0,n*pitch,pitch):lower[hi+offset]=[lo+offset];upper[lo+offset]=[hi+offset]
 pairs=ints(text,'symmetricCaseConversions')
 for lo,hi in zip(pairs[::2],pairs[1::2]):lower[hi]=[lo];upper[lo]=[hi]
 block=re.search(r'complexCaseConversions\s*=(.*?);',text,re.S)[1]
 fields=b''.join(ast.literal_eval('b'+s) for s in re.findall(r'^\s*(".*")\s*$',block,re.M)).split(b'|')
 assert fields.pop()==b'' and len(fields)%4==0
 for i in range(0,len(fields),4):
  origin,fold,up,lo=fields[i:i+4];cp=ord(origin.decode())
  if lo:lower[cp]=[ord(c) for c in lo.decode()]
  if up:upper[cp]=[ord(c) for c in up.decode()]
 return [{k:v for k,v in sorted(m.items()) if v!=[k]} for m in (lower,upper)]
def word_class(cp,category):
 if cp<128:
  if cp in (10,13):return 3
  if cp<=32 or cp==127:return 0
  return 1 if chr(cp).isascii() and (chr(cp).isalnum() or cp==95) else 2
 return 1 if category<=10 else 2 if category<=21 else 3 if category in (23,24) else 0
text=source('CaseConvert.cxx');lower,upper=maps(text)
raw=ints(source('CharacterCategoryMap.cxx'),'catRanges')
# catRanges encodes (rangeStart <<5)|category; preserve category changes only where word class changes.
classes=[]
for i,value in enumerate(raw):
 start=value>>5;end=(raw[i+1]>>5) if i+1<len(raw) else 0x110000
 if start>=0x110000:break
 for at,to in ((start,min(end,128)),(max(start,128),end)):
  if at>=to:continue
  if at<128:
   for cp in range(at,to):
    c=word_class(cp,value&31)
    if not classes or classes[-1][1]!=c:classes.append((cp,c))
  else:
   c=word_class(at,value&31)
   if not classes or classes[-1][1]!=c:classes.append((at,c))
header='''// Generated by scripts/generate-unified-case-mapping.py; do not edit.
// Scintilla CaseConvert/CharacterCategoryMap, Copyright 2013 Neil Hodgson.
// Scintilla license and attribution are retained in NOTICE.
// Pinned upstream: '''+pin+'''
// No locale or host Unicode-version classification is used.
enum UnifiedDiffCaseMapping {
'''
def table(name,m):return '    static let '+name+': [UInt32: [UInt32]] = [\n'+''.join('        0x%X: [%s],\n'%(k,', '.join('0x%X'%v for v in vals)) for k,vals in m.items())+'    ]\n'
generated=header+table('lower',lower)+table('upper',upper)+'    // 0=space,1=word,2=punctuation,3=newline. Sorted inclusive starts.\n    static let wordClasses: [(UInt32, Int)] = [\n'+''.join('        (0x%X, %d),\n'%r for r in classes)+'    ]\n}\n'
target=root/'Sources/TurtleGitCore/UnifiedDiffCaseMapping.generated.swift'
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');p.add_argument('--write',action='store_true');args=p.parse_args()
if args.check:
 assert target.read_text()==generated,'Pinned mapping file needs regeneration'
 with tempfile.TemporaryDirectory(prefix='turtlegit-case-map-') as tmp:
  d=Path(tmp)
  for name in ['CaseConvert.cxx','CaseConvert.h','UniConversion.cxx','UniConversion.h','CharacterCategoryMap.cxx','CharacterCategoryMap.h','CharClassify.cxx','CharClassify.h','CharacterType.h']:(d/name).write_text(source(name))
  document=source('Document.cxx')
  methodStart=document.index('CharacterClass Document::WordCharacterClass(')
  brace=document.index('{',methodStart);depth=1;end=brace+1
  while depth:
   if document[end]=='{':depth+=1
   elif document[end]=='}':depth-=1
   end+=1
  method=document[methodStart:end].replace('Document::WordCharacterClass','Probe::WordCharacterClass',1)
  (d/'main.cpp').write_text(r'''
#include <iostream>
#include <string>
#include <cstddef>
#include <vector>
#include <string_view>
#include <algorithm>
#include "CaseConvert.h"
#include "CharacterCategoryMap.h"
#include "CharClassify.h"
namespace Scintilla::Internal {
constexpr int CpUtf8=65001;
struct Probe {int dbcsCodePage=CpUtf8;CharacterCategoryMap charMap;CharClassify charClass;CharacterClass WordCharacterClass(unsigned int ch)const;};
''' + method + r'''
}
int main(){using namespace Scintilla::Internal;Probe probe;for(int cp=0;cp<=0x10ffff;cp++){if(cp>=0xd800&&cp<=0xdfff)continue;std::cout<<cp<<'\t'<<int(probe.WordCharacterClass(cp));for(auto mode:{CaseConversion::lower,CaseConversion::upper}){std::cout<<'\t';const char* p=CaseConvert(cp,mode);if(p)for(const unsigned char* q=reinterpret_cast<const unsigned char*>(p);*q;q++)std::cout<<"0123456789abcdef"[*q>>4]<<"0123456789abcdef"[*q&15];}std::cout<<'\n';}}
''')
  exe=d/'reference';subprocess.run(['xcrun','clang++','-std=c++17','-O2',str(d/'main.cpp'),str(d/'CaseConvert.cxx'),str(d/'UniConversion.cxx'),str(d/'CharacterCategoryMap.cxx'),str(d/'CharClassify.cxx'),'-o',str(exe)],check=True,timeout=120)
  cursor=0;actual=[{},{}]
  for line in subprocess.check_output([str(exe)],text=True,timeout=60).splitlines():
   cp,category,lo,up=line.split('\t');cp=int(cp)
   reference_class={0:0,1:3,2:1,3:2}[int(category)]
   while cursor+1<len(classes) and classes[cursor+1][0]<=cp:cursor+=1
   assert classes[cursor][1]==reference_class,('word class',cp)
   for n,value in enumerate((lo,up)):
    if value:
     mapped=[ord(c) for c in bytes.fromhex(value).decode()]
     if mapped!=[cp]:actual[n][cp]=mapped
  assert actual==[lower,upper],'Case conversion differs from pinned C++'
 print('PASS: lower/upper and word classes checked against pinned C++ for every valid Unicode scalar')
else:
 target.write_text(generated);print('Generated',len(lower),'lower,',len(upper),'upper,',len(classes),'word-class ranges')
