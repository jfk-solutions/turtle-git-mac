#!/usr/bin/env python3
"""Generate the native literal-search fold table from pinned Scintilla sources.

--check also compares every Unicode scalar against the original C++ converter.
"""
import argparse
import ast
import csv
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tempfile
import urllib.request
root=Path(__file__).resolve().parent.parent
pin=json.loads((root/'docs/upstream.json').read_text())['commit']
with (root/'docs/upstream-files.csv').open(newline='') as f:blobs={r['path']:r['blob'] for r in csv.DictReader(f)}

def source(name):
    path='ext/scintilla/src/'+name;checkout=root/'.upstream/TortoiseGit';cache=root/'build/qa/unified-find-source'/pin/name
    if (checkout/'.git').exists():data=subprocess.check_output(['git','-C',str(checkout),'show',pin+':'+path])
    elif cache.exists():data=cache.read_bytes()
    else:
        with urllib.request.urlopen('https://raw.githubusercontent.com/TortoiseGit/TortoiseGit/'+pin+'/'+path,timeout=30) as stream:data=stream.read()
    assert hashlib.sha1(b'blob '+str(len(data)).encode()+b'\0'+data).hexdigest()==blobs[path],path
    cache.parent.mkdir(parents=True,exist_ok=True);cache.write_bytes(data)
    return data.decode('utf-8-sig').replace('\r\n','\n')

def mappings(text):
    result={}
    def put(key,value):
        if key in result and result[key]!=value:raise ValueError('Ambiguous upstream folding '+str(key))
        result[key]=value
    def integers(name):
        block=re.search(r'\b'+name+r'\[\]\s*=\s*\{(.*?)\};',text,re.S)[1]
        block=re.sub(r'//[^\n]*','',block)
        return [int(value) for value in re.findall(r'-?\d+',block)]
    ranges=integers('symmetricCaseConversionRanges')
    for i in range(0,len(ranges),4):
        lower,upper,length,pitch=ranges[i:i+4]
        for offset in range(0,length*pitch,pitch):put(upper+offset,[lower+offset])
    pairs=integers('symmetricCaseConversions')
    for i in range(0,len(pairs),2):put(pairs[i+1],[pairs[i]])
    block=re.search(r'complexCaseConversions\s*=(.*?);',text,re.S)[1]
    raw=b''.join(ast.literal_eval('b'+literal) for literal in re.findall(r'^\s*(".*")\s*$',block,re.M))
    fields=raw.split(b'|');assert fields[-1]==b'';fields=fields[:-1]
    assert len(fields)%4==0
    for i in range(0,len(fields),4):
        origin,folded,_,_=fields[i:i+4]
        if folded:put(ord(origin.decode()),[ord(c) for c in folded.decode()])
    return {key:value for key,value in sorted(result.items()) if value!=[key]}

def swift(table):
    header='''// Generated by scripts/generate-unified-case-fold.py; do not edit the table.
// Scintilla CaseConvert.cxx, Copyright 2013 Neil Hodgson <neilh@scintilla.org>.
// Scintilla License.txt terms and attribution are reproduced in NOTICE.
// Pinned upstream: '''+pin+'''
// Locale-independent folding; no canonical or compatibility normalization.
enum UnifiedDiffCaseFold {
    static let mappings: [UInt32: [UInt32]] = [
'''
    return header+''.join('        0x%X: [%s],\n'%(key,', '.join('0x%X'%v for v in value)) for key,value in table.items())+'    ]\n}\n'

parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
text=source('CaseConvert.cxx');table=mappings(text);target=root/'Sources/TurtleGitCore/UnifiedDiffCaseFold.swift';generated=swift(table)
if args.check:
    assert target.read_text()==generated,'Regenerate the pinned native case-fold table.'
    with tempfile.TemporaryDirectory(prefix='turtlegit-case-fold-') as temporary:
        folder=Path(temporary)
        for name in ['CaseConvert.cxx','CaseConvert.h','UniConversion.cxx','UniConversion.h']:(folder/name).write_text(source(name))
        (folder/'main.cpp').write_text(r'''
#include <iostream>
#include <string>
#include <cstddef>
#include "CaseConvert.h"
int main() {
 using namespace Scintilla::Internal;
 for(int cp=0;cp<=0x10FFFF;cp++) {
  if(cp>=0xD800 && cp<=0xDFFF) continue;
  const char *folded=CaseConvert(cp,CaseConversion::fold);
  if(!folded) continue;
  std::cout<<cp<<'\t';
  for(const unsigned char *p=reinterpret_cast<const unsigned char *>(folded);*p;p++) std::cout<<"0123456789abcdef"[*p>>4]<<"0123456789abcdef"[*p&15];
  std::cout<<'\n';
 }
}
''')
        executable=folder/'converter'
        subprocess.run(['xcrun','clang++','-std=c++17','-O2',str(folder/'main.cpp'),str(folder/'CaseConvert.cxx'),str(folder/'UniConversion.cxx'),'-o',str(executable)],check=True,timeout=120)
        actual={}
        for line in subprocess.check_output([str(executable)],text=True,timeout=30).splitlines():
            key,value=line.split('\t');scalars=[ord(c) for c in bytes.fromhex(value).decode()]
            if scalars!=[int(key)]:actual[int(key)]=scalars
        assert actual==table,'Generated native mappings differ from pinned C++ converter.'
    print('PASS: all 1,112,064 valid Unicode scalars checked against pinned C++ CaseConvert; '+str(len(table))+' nonidentity native mappings.')
else:
    target.write_text(generated);print('Generated '+str(len(table))+' pinned Scintilla case-fold mappings.')
