import Foundation

/// MainFrm::OnEditCreateunifieddifffile replaces temporary-file header names
/// with repository-relative reflected names after Git creates a two-file patch.
/// Reflected names are display metadata, never an input/output authority grant.
public enum MergeReflectedPatch {
    public struct Labels: Sendable {
        public let base: String
        public let destination: String
        public init(base: String, destination: String) { self.base = base; self.destination = destination }
    }

    /// Source rewriting is limited to ordinary text patches with an index line
    /// followed by old/new headers and a hunk. Binary, mode-only, added/deleted,
    /// empty and unrecognised Git output retain their original generated bytes.
    public static func rewrite(_ patch: Data, baseReflectedName: String?, destinationReflectedName: String?,
                               executable: URL, cancellation: OperationCancellation? = nil) async throws -> Data {
        try cancellation?.check()
        guard eligible(patch), let labels = try await labels(baseReflectedName: baseReflectedName,
            destinationReflectedName: destinationReflectedName, executable: executable, cancellation: cancellation) else { return patch }
        try cancellation?.check()
        return rewritingHeaders(in: patch, labels: labels)
    }

    /// Only a common working-tree root permits rewriting. Separate linked
    /// worktrees sharing an object database still have distinct source roots.
    /// Discovery runs through Git without a shell and never opens either file.
    /// Missing descendants are permitted, as in GitAdminDir::HasAdminDir.
    public static func labels(baseReflectedName: String?, destinationReflectedName: String?,
                              executable: URL, cancellation: OperationCancellation? = nil) async throws -> Labels? {
        try cancellation?.check()
        guard let base = absolutePath(baseReflectedName), let destination = absolutePath(destinationReflectedName),
              let baseRoot = try await workingRoot(for: base, executable: executable, cancellation: cancellation),
              let destinationRoot = try await workingRoot(for: destination, executable: executable, cancellation: cancellation),
              baseRoot.utf8.elementsEqual(destinationRoot.utf8) else { return nil }
        let prefix = baseRoot == "/" ? "/" : baseRoot + "/"
        guard base.utf8.starts(with: prefix.utf8), destination.utf8.starts(with: prefix.utf8) else { return nil }
        let old = String(decoding: base.utf8.dropFirst(prefix.utf8.count), as: UTF8.self)
        let new = String(decoding: destination.utf8.dropFirst(prefix.utf8.count), as: UTF8.self)
        guard !old.isEmpty, !new.isEmpty else { return nil }
        return Labels(base: old, destination: new)
    }

    /// Kept separate from discovery so byte-preserving output can be checked
    /// without needing an actual repository or decoding arbitrary hunk payloads.
    public static func rewritingHeaders(in patch: Data, labels: Labels) -> Data {
        guard eligible(patch), [labels.base, labels.destination].allSatisfy({ !$0.isEmpty && !$0.contains("\0") }) else { return patch }
        let lines = patch.split(separator: 10, omittingEmptySubsequences: false)
        let old = quotedPath("a/" + labels.base), new = quotedPath("b/" + labels.destination)
        var result = Data("diff --git \(old) \(new)\n".utf8)
        result.append(contentsOf: lines[1]); result.append(10)
        result.append(Data("--- \(old)\n+++ \(new)\n".utf8))
        for index in 4..<lines.count {
            if index > 4 { result.append(10) }
            result.append(contentsOf: lines[index])
        }
        return result
    }

    private static func eligible(_ patch: Data) -> Bool {
        let lines = patch.split(separator: 10, maxSplits: 5, omittingEmptySubsequences: false)
        return lines.count >= 5 && lines[0].starts(with: "diff --git ".utf8) && lines[1].starts(with: "index ".utf8)
            && lines[2].starts(with: "--- ".utf8) && lines[3].starts(with: "+++ ".utf8) && lines[4].starts(with: "@@ ".utf8)
            && !lines[2].elementsEqual("--- /dev/null".utf8) && !lines[3].elementsEqual("+++ /dev/null".utf8)
    }
    private static func absolutePath(_ value: String?) -> String? {
        guard let value, value.hasPrefix("/"), !value.contains("\0") else { return nil }
        let path = FileTransferPaths.lexicalPath(value)
        // Source excludes .git and descendants from working-copy discovery.
        guard !path.split(separator: "/").contains(".git") else { return nil }
        return path
    }
    private static func workingRoot(for path: String, executable: URL, cancellation: OperationCancellation?) async throws -> String? {
        var directory = String(path[..<(path.lastIndex(of: "/") ?? path.startIndex)])
        if directory.isEmpty { directory = "/" }
        while true {
            try cancellation?.check()
            var isDirectory: ObjCBool = false
            if FileManager.default.fileExists(atPath: directory, isDirectory: &isDirectory), isDirectory.boolValue { break }
            guard directory != "/" else { return nil }
            directory = String(directory[..<(directory.lastIndex(of: "/") ?? directory.startIndex)])
            if directory.isEmpty { directory = "/" }
        }
        let repository = GitRepository(root: FileTransferPaths.fileURL(directory), executable: executable)
        do {
            guard try await repository.isBare(cancellation: cancellation) == false else { return nil }
            let output = try await repository.run(["rev-parse", "--show-toplevel"], cancellation: cancellation).stdout
            try cancellation?.check()
            var bytes = output
            if bytes.last == 10 { bytes.removeLast() }
            guard let root = String(data: bytes, encoding: .utf8), root.hasPrefix("/"), !root.contains("\0") else { return nil }
            // Git canonicalises /var and other system aliases. Find that same
            // root among the original lexical ancestors by filesystem identity,
            // retaining the caller's exact spelling for relative UTF-8 labels.
            let actual = try FileManager.default.attributesOfItem(atPath: root)
            guard let device = actual[.systemNumber] as? NSNumber, let inode = actual[.systemFileNumber] as? NSNumber else { return nil }
            var candidate = directory
            while true {
                try cancellation?.check()
                if let attributes = try? FileManager.default.attributesOfItem(atPath: candidate),
                   let candidateDevice = attributes[.systemNumber] as? NSNumber,
                   let candidateInode = attributes[.systemFileNumber] as? NSNumber,
                   device.isEqual(to: candidateDevice), inode.isEqual(to: candidateInode) { return candidate }
                guard candidate != "/" else { return nil }
                candidate = String(candidate[..<(candidate.lastIndex(of: "/") ?? candidate.startIndex)])
                if candidate.isEmpty { candidate = "/" }
            }
        } catch {
            try cancellation?.check()
            return nil
        }
    }
    /// Always quoted as in the source rewrite, with Git's C-style escaping so
    /// quotes, backslashes, control characters and UTF-8 bytes remain literal.
    private static func quotedPath(_ value: String) -> String {
        "\"" + value.utf8.map { byte -> String in
            switch byte {
            case 34: return "\\\""
            case 92: return "\\\\"
            case 9: return "\\t"
            case 10: return "\\n"
            case 13: return "\\r"
            case 32...126: return String(UnicodeScalar(byte))
            default: return String(format: "\\%03o", Int(byte))
            }
        }.joined() + "\""
    }
}
